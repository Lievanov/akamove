create table
  public.student (
    id uuid not null default gen_random_uuid (),
    created_at timestamp with time zone not null default now(),
    first_name text not null,
    last_name text not null,
    date_of_birth date null,
    email text null,
    phone text null,
    notes text null,
    is_active boolean null default true,
    classes uuid[] null,
    constraint student_pkey primary key (id)
  ) tablespace pg_default;

  create table
  public.class_type (
    id bigint generated by default as identity not null,
    created_at timestamp with time zone not null default now(),
    name text not null,
    constraint class_type_pkey primary key (id)
  ) tablespace pg_default;

  create table
  public.class (
    id uuid not null default gen_random_uuid (),
    created_at timestamp with time zone not null default now(),
    name text not null,
    level bigint null,
    "order" integer null,
    class_type integer null,
    constraint classes_pkey primary key (id)
  ) tablespace pg_default;

  create table
  public.period (
    id uuid not null default gen_random_uuid (),
    created_at timestamp with time zone not null default now(),
    start_date date null,
    end_date date null,
    classes uuid[] null,
    constraint Period_pkey primary key (id)
  ) tablespace pg_default;

  create table
  public.payment (
    id uuid not null default gen_random_uuid (),
    student_id uuid not null,
    classes uuid[] not null,
    payment_method text null,
    payment_amount numeric null,
    created_at timestamp with time zone not null default now(),
    period_id uuid not null default gen_random_uuid (),
    notes text null,
    constraint payment_pkey primary key (id),
    constraint payment_period_id_fkey foreign key (period_id) references period (id),
    constraint payment_studentId_fkey foreign key (student_id) references student (id)
  ) tablespace pg_default;

create table
  public.profiles (
    id uuid not null references auth.users on delete cascade,
    full_name text,
    email text unique,
    avatar_url text,
    role text not null default 'staff',
    primary key (id)
  );

alter table profiles enable row level security;

create policy "Public profiles are viewable by everyone." on profiles for
select
  using (true);

create policy "Users can insert their own profile." on profiles for insert
with
  check (auth.uid () = id);

create policy "Users can update own profile." on profiles
for update
  using (auth.uid () = id);

create function public.handle_new_user () returns trigger as $$
begin
  insert into public.profiles (id, full_name, avatar_url, email)
  values (
    new.id, 
    new.raw_user_meta_data->>'full_name', 
    new.raw_user_meta_data->>'avatar_url',
    new.raw_user_meta_data->>'email'
    );
  return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
after insert on auth.users for each row
execute procedure public.handle_new_user ();

-- DROP VIEW classes_by_student_view;
CREATE VIEW classes_by_student_view WITH (security_invoker=on) AS
SELECT
    s.id AS id,
    s.first_name AS first_name,
    s.last_name AS last_name,
    s.phone AS phone,
    s.created_at AS created_at,
    c.class_type AS class_type,
    c.name || ' ' || c.level AS class_info,
    class_id_array AS class_id,
    per.id AS period_id,
    per.name as period_name
FROM
    student AS s
INNER JOIN
    payment AS pay ON s.id = pay.student_id
INNER JOIN
    unnest(pay.classes) AS class_id_array ON TRUE
INNER JOIN
    class AS c ON c.id = class_id_array
INNER JOIN
    period AS per ON per.id = pay.period_id
GROUP BY
    s.id,
    s.first_name,
    s.last_name,
    class_type,
    class_info,
    class_id_array,
    per.id,
    per.name;

-- Private lessons: active/inactive flag.
-- A lesson package is marked inactive once all purchased lessons are consumed
-- (handled in app logic), or manually via the toggle in the dashboard.
ALTER TABLE private_lessons
    ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;

-- Backfill: any package that has already used all its lessons becomes inactive.
UPDATE private_lessons
SET is_active = false
WHERE lessons_used >= lessons_purchased;

-- Recreate the view so is_active is exposed to the dashboard.
DROP VIEW IF EXISTS private_lessons_view;
CREATE VIEW private_lessons_view WITH (security_invoker = on) AS
SELECT
    pl.id,
    pl.student_id,
    pl.instructor_id,
    pl.lessons_purchased,
    pl.lessons_used,
    pl.date_purchased,
    pl.amount,
    pl.is_active,
    s.first_name,
    s.last_name,
    i.name AS instructor_name
FROM private_lessons AS pl
LEFT JOIN student AS s ON s.id = pl.student_id
LEFT JOIN instructors AS i ON i.id = pl.instructor_id;
